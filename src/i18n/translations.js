let language = 'fa'
const listeners = new Set()

function lookup(dict, path) {
  return path.split('.').reduce((acc, part) => (acc == null ? acc : acc[part]), dict)
}

function interpolate(template, params) {
  if (!params) return template
  return String(template).replace(/\{(\w+)\}/g, (_, key) =>
    params[key] == null ? `{${key}}` : String(params[key]),
  )
}

export function getLanguage() {
  return language
}

export function setLanguage(next) {
  const lang = next === 'en' ? 'en' : 'fa'
  if (lang === language) return language
  language = lang
  listeners.forEach((fn) => fn(lang))
  return language
}

export function subscribeLanguage(fn) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

export function t(key, params) {
  const primary = lookup(translations[language], key)
  const fallback = lookup(translations.fa, key)
  const template = primary ?? fallback ?? key
  return interpolate(template, params)
}

export function formatNumber(value) {
  const n = Number(value) || 0
  return n.toLocaleString(language === 'en' ? 'en-US' : 'fa-IR')
}

export function subscriptionLabel(type) {
  if (type === 'gold') return t('common.subscriptionGold')
  if (type === 'silver') return t('common.subscriptionSilver')
  return t('common.subscriptionBasic')
}

export function genderLabel(value) {
  switch (value) {
    case 'female':
      return t('common.genderFemale')
    case 'male':
      return t('common.genderMale')
    case 'other':
      return t('common.genderOther')
    case 'unspecified':
      return t('common.genderUnspecified')
    default:
      return value || '—'
  }
}
